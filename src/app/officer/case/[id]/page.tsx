"use client";

import { useParams } from "next/navigation";
import { useState } from "react";
import { Download, FileText, Loader2 } from "lucide-react";
import { DRAFT_TYPES, runDraft, runPlan, type DraftType } from "@/lib/pipeline";
import { ErrorBox, Markdown, download } from "@/components/ui";
import { AuditTrail, CaseHeader, DirectionCard, Gate, Progress, useCase } from "@/components/case";

export default function OfficerCase() {
  const { id } = useParams<{ id: string }>();
  const { b, error, setError, live, run, reload } = useCase(id);
  const [busy, setBusy] = useState<string | null>(null);

  if (!b) return error ? <ErrorBox error={error} /> : <Loader2 className="animate-spin text-brand" />;
  const stage = b.order.pipeline_stage;
  const plan = b.drafts.find((d) => d.type === "plan");
  const drafts = b.drafts.filter((d) => d.type !== "plan" && d.type !== "citizen_explanation");
  const verified = b.directions.filter((d) => d.status === "verified");

  async function doPlan() {
    setBusy("plan"); setError(null);
    try { await runPlan(id); await reload(); } catch (e) { setError(e instanceof Error ? e.message : "Failed"); } finally { setBusy(null); }
  }
  async function doDraft(t: DraftType) {
    setBusy(t); setError(null);
    try { await runDraft(id, t); await reload(); } catch (e) { setError(e instanceof Error ? e.message : "Failed"); } finally { setBusy(null); }
  }

  return (
    <div className="space-y-6">
      <CaseHeader b={b} />
      <Progress stage={stage} live={live} error={error} onRetry={run} />

      {stage === "no_directions" && (
        <div className="card p-4">
          <h2 className="font-semibold">No directions to a government party</h2>
          <p className="mt-1 text-sm text-muted">{b.order.extractor_notes ?? "The extractor found nothing to track."}</p>
        </div>
      )}

      {stage === "awaiting_gate" && <Gate b={b} onDone={reload} />}

      {(stage === "verified" || stage === "planned") && (
        <>
          <section className="card space-y-4 p-4">
            <div className="flex flex-wrap items-center justify-between gap-3">
              <div>
                <h2 className="text-lg font-semibold">Compliance plan</h2>
                <p className="text-sm text-muted">Dates and statuses are computed by the system; the Planner explains them. {verified.length} verified direction(s).</p>
              </div>
              <button className="btn-primary" disabled={!!busy || verified.length === 0} onClick={doPlan}>
                {busy === "plan" && <Loader2 size={16} className="animate-spin" />} {plan ? "Rebuild plan" : "Build compliance plan"}
              </button>
            </div>
            <div className="space-y-3">
              {b.directions.map((d) => <DirectionCard key={d.id} d={d} tasks={b.tasks.filter((t) => t.direction_id === d.id)} onChange={reload} />)}
            </div>
            {plan && <div className="rounded-2xl bg-lavender p-4"><Markdown>{plan.content}</Markdown><p className="mt-2 text-xs text-muted">Generated by {plan.model_used} · {new Date(plan.created_at).toLocaleString()}</p></div>}
          </section>

          <section className="card space-y-4 p-4">
            <h2 className="text-lg font-semibold">Drafts</h2>
            <p className="text-sm text-muted">Every draft is marked &ldquo;DRAFT – FOR REVIEW ONLY&rdquo;, uses [BLANKS] for unknown facts, and never recommends appeal or compliance.</p>
            <div className="flex flex-wrap gap-2">
              {(Object.keys(DRAFT_TYPES) as DraftType[]).map((t) => (
                <button key={t} className="btn-ghost" disabled={!!busy || verified.length === 0} onClick={() => doDraft(t)}>
                  {busy === t ? <Loader2 size={14} className="animate-spin" /> : <FileText size={14} />} {DRAFT_TYPES[t]}
                </button>
              ))}
            </div>
            {drafts.map((d) => (
              <details key={d.id} className="rounded-2xl border border-line" open={d === drafts[0]}>
                <summary className="flex cursor-pointer items-center gap-3 px-4 py-3 text-sm">
                  <b>{DRAFT_TYPES[d.type as DraftType] ?? d.type}</b>
                  <span className="text-muted">{new Date(d.created_at).toLocaleString()} · {d.model_used}</span>
                  <button className="ml-auto text-brand" onClick={(e) => { e.preventDefault(); download(`${d.type}-${b.order.case_number ?? "case"}.md`, d.content); }}><Download size={16} /></button>
                </summary>
                <div className="border-t border-line p-4"><Markdown>{d.content}</Markdown></div>
              </details>
            ))}
          </section>
        </>
      )}

      {b.directions.length > 0 && <AuditTrail b={b} />}
    </div>
  );
}
